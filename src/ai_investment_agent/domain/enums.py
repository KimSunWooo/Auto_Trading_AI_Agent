class KillSwitchLevel(str, Enum):
    """Proposal-only kill switch. This project never stops a live trading system.

    LEVEL_4_ALL_TRADING_DISABLED is not FORCE_SELL_ALL.
    """

    LEVEL_0_NORMAL = "LEVEL_0_NORMAL"
    LEVEL_1_NO_NEW_BUY = "LEVEL_1_NO_NEW_BUY"
    LEVEL_2_REDUCE_EXPOSURE = "LEVEL_2_REDUCE_EXPOSURE"
    LEVEL_3_AI_DISABLED = "LEVEL_3_AI_DISABLED"
    LEVEL_4_ALL_TRADING_DISABLED = "LEVEL_4_ALL_TRADING_DISABLED"

    @property
    def rank(self) -> int:
        return {
            KillSwitchLevel.LEVEL_0_NORMAL: 0,
            KillSwitchLevel.LEVEL_1_NO_NEW_BUY: 1,
            KillSwitchLevel.LEVEL_2_REDUCE_EXPOSURE: 2,
            KillSwitchLevel.LEVEL_3_AI_DISABLED: 3,
            KillSwitchLevel.LEVEL_4_ALL_TRADING_DISABLED: 4,
        }[self]



from __future__ import annotations

from enum import Enum


class Horizon(str, Enum):
    LONG_TERM = "LONG_TERM"
    SHORT_TERM = "SHORT_TERM"
    NONE = "NONE"


class Action(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    NO_TRADE = "NO_TRADE"
    TACTICAL_WAIT = "TACTICAL_WAIT"
    EXIT_REVIEW = "EXIT_REVIEW"


class DecisionType(str, Enum):
    """Canonical judgment outcomes this agent can emit."""

    LONG_TERM_BUY = "LONG_TERM_BUY"
    SHORT_TERM_BUY = "SHORT_TERM_BUY"
    HOLD = "HOLD"
    SELL = "SELL"
    NO_TRADE = "NO_TRADE"
    TACTICAL_WAIT = "TACTICAL_WAIT"
    EXIT_REVIEW = "EXIT_REVIEW"


class MarketRegimeType(str, Enum):
    BULL = "BULL"
    BEAR = "BEAR"
    SIDEWAYS = "SIDEWAYS"
    HIGH_VOLATILITY = "HIGH_VOLATILITY"
    CRISIS = "CRISIS"
    UNKNOWN = "UNKNOWN"


class EventSeverity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class AgentPriority(str, Enum):
    """Ordered priorities. Opportunity seeking is last, never first."""

    CAPITAL_PRESERVATION = "CAPITAL_PRESERVATION"
    CATASTROPHIC_LOSS_PREVENTION = "CATASTROPHIC_LOSS_PREVENTION"
    RISK_ADJUSTED_RETURN = "RISK_ADJUSTED_RETURN"
    STABLE_JUDGMENT = "STABLE_JUDGMENT"
    OPPORTUNITY_SEEKING = "OPPORTUNITY_SEEKING"


class JournalStage(str, Enum):
    DATA = "DATA"
    ANALYSIS = "ANALYSIS"
    RISK_ASSESSMENT = "RISK_ASSESSMENT"
    DECISION = "DECISION"
    TRADE_PROPOSAL = "TRADE_PROPOSAL"


class ReasonCode(str, Enum):
    UNKNOWN_MARKET_REGIME = "UNKNOWN_MARKET_REGIME"
    CAPITAL_CONTEXT_MISSING = "CAPITAL_CONTEXT_MISSING"
    ZERO_DEPLOYABLE_CAPITAL = "ZERO_DEPLOYABLE_CAPITAL"
    CAPITAL_PRESERVATION_PRIORITY = "CAPITAL_PRESERVATION_PRIORITY"
    CATASTROPHIC_LOSS_PREVENTION = "CATASTROPHIC_LOSS_PREVENTION"
    POLICY_NO_TRADE_IS_VALID = "POLICY_NO_TRADE_IS_VALID"
    FIXTURE_DECISION = "FIXTURE_DECISION"
    BUY_REQUIRES_HORIZON = "BUY_REQUIRES_HORIZON"
    LOW_DATA_COMPLETENESS = "LOW_DATA_COMPLETENESS"
